//! Local HTTP test server for Mohona.
//!
//! It serves generated, deterministic content, so a 1 GiB file needs no disk
//! space, and it can misbehave on purpose. That lets the download engine be
//! tested against slow, flaky and unusual servers.
//!
//! Every response closes or keeps the connection according to the request's
//! `Connection` header (HTTP/1.1 keep-alive is the default).

use std::collections::HashMap;
use std::io;
use std::net::SocketAddr;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use tokio::io::{AsyncBufReadExt, AsyncWrite, AsyncWriteExt, BufReader};
use tokio::net::{TcpListener, TcpStream};

/// Default size of the generated file: 1 GiB.
pub const DEFAULT_SIZE: u64 = 1 << 30;

/// Help text printed at startup and served at `/` and `/info`.
pub const USAGE: &str = "\
Mohona test server

Endpoints
  /file       the generated file, with HTTP Range support
  /redirect   302 redirect to /file, keeping the query string
  /auth       like /file, but needs Basic auth (user: mohona, password: secret)
  /login      sets the cookie session=ok
  /cookie     like /file, but needs the cookie session=ok
  /referrer   like /file, but needs a Referer header

Query parameters (for /file and the endpoints that serve it)
  size=<bytes>        file size (default: the server's --size)
  etag=<text>         change the ETag, to test files that change between runs
  limit=<bytes/sec>   throttle each connection to this speed
  slow_start=<bytes/sec>  throttle only the response that begins at byte 0,
                      so one segment lags behind the others
  drop_after=<bytes>  close the connection after this many body bytes
  drop=random         close the connection after a random number of body bytes
  norange=1           ignore Range requests (answer 200 with the whole file)
  nohead=1            answer HEAD requests with 405

Byte N of the file is a fixed function of N, so a client can verify any
range without keeping a copy of the file.
";

const CHUNK: usize = 16 * 1024;
const MAX_HEADERS: usize = 100;
/// `Authorization` header value for user `mohona`, password `secret`.
const BASIC_AUTH: &str = "Basic bW9ob25hOnNlY3JldA==";
const LAST_MODIFIED: &str = "Wed, 01 Jan 2025 00:00:00 GMT";

/// Server settings.
#[derive(Clone, Debug)]
pub struct Config {
    /// Size of `/file` when the request has no `size` parameter.
    pub default_size: u64,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            default_size: DEFAULT_SIZE,
        }
    }
}

/// The byte at `offset` in the generated file.
pub fn content_byte(offset: u64) -> u8 {
    (offset.wrapping_mul(0x9E37_79B9_7F4A_7C15) >> 56) as u8
}

/// Fill `buf` with the generated bytes starting at `offset`.
pub fn fill_content(offset: u64, buf: &mut [u8]) {
    for (i, byte) in buf.iter_mut().enumerate() {
        *byte = content_byte(offset + i as u64);
    }
}

/// Parse the first range of a `Range` header against a file of `size` bytes.
///
/// Returns the inclusive `(start, end)` or `None` if the header is malformed
/// or cannot be satisfied.
pub fn parse_range(header: &str, size: u64) -> Option<(u64, u64)> {
    let spec = header.strip_prefix("bytes=")?.split(',').next()?.trim();
    let (first, last) = spec.split_once('-')?;
    if size == 0 {
        return None;
    }
    if first.is_empty() {
        let count: u64 = last.parse().ok()?;
        if count == 0 {
            return None;
        }
        return Some((size.saturating_sub(count), size - 1));
    }
    let start: u64 = first.parse().ok()?;
    if start >= size {
        return None;
    }
    let end = if last.is_empty() {
        size - 1
    } else {
        last.parse::<u64>().ok()?.min(size - 1)
    };
    if end < start {
        return None;
    }
    Some((start, end))
}

/// Bind a listener. Use port 0 to let the operating system pick a free port.
pub async fn bind(addr: SocketAddr) -> io::Result<TcpListener> {
    TcpListener::bind(addr).await
}

/// Accept connections forever.
pub async fn serve(listener: TcpListener, config: Config) -> io::Result<()> {
    loop {
        let (stream, _) = listener.accept().await?;
        let config = config.clone();
        tokio::spawn(async move {
            let _ = handle_connection(stream, config).await;
        });
    }
}

struct Request {
    method: String,
    path: String,
    raw_query: String,
    query: HashMap<String, String>,
    /// Header names are lowercased.
    headers: HashMap<String, String>,
}

async fn handle_connection(stream: TcpStream, config: Config) -> io::Result<()> {
    let _ = stream.set_nodelay(true);
    let (read_half, mut writer) = stream.into_split();
    let mut reader = BufReader::new(read_half);
    loop {
        let Some(request) = read_request(&mut reader).await? else {
            return Ok(());
        };
        let keep_alive = !request
            .headers
            .get("connection")
            .is_some_and(|value| value.eq_ignore_ascii_case("close"));
        let keep_open = route(&request, &mut writer, &config, keep_alive).await?;
        if !keep_open {
            return Ok(());
        }
    }
}

async fn read_request<R: AsyncBufReadExt + Unpin>(reader: &mut R) -> io::Result<Option<Request>> {
    let mut line = String::new();
    if reader.read_line(&mut line).await? == 0 {
        return Ok(None);
    }
    let mut parts = line.split_whitespace();
    let (Some(method), Some(target)) = (parts.next(), parts.next()) else {
        return Ok(None);
    };
    let method = method.to_string();
    let (path, raw_query) = target.split_once('?').unwrap_or((target, ""));
    let path = path.to_string();
    let raw_query = raw_query.to_string();

    let mut headers = HashMap::new();
    for _ in 0..MAX_HEADERS {
        line.clear();
        if reader.read_line(&mut line).await? == 0 {
            return Ok(None);
        }
        let text = line.trim_end();
        if text.is_empty() {
            break;
        }
        if let Some((name, value)) = text.split_once(':') {
            headers.insert(name.trim().to_ascii_lowercase(), value.trim().to_string());
        }
    }

    let query = raw_query
        .split('&')
        .filter(|pair| !pair.is_empty())
        .map(|pair| match pair.split_once('=') {
            Some((key, value)) => (key.to_string(), value.to_string()),
            None => (pair.to_string(), String::new()),
        })
        .collect();

    Ok(Some(Request {
        method,
        path,
        raw_query,
        query,
        headers,
    }))
}

fn connection_word(keep_alive: bool) -> &'static str {
    if keep_alive {
        "keep-alive"
    } else {
        "close"
    }
}

async fn simple<W: AsyncWrite + Unpin>(
    writer: &mut W,
    status: &str,
    body: &str,
    extra: &[(&str, &str)],
    keep_alive: bool,
    head_only: bool,
) -> io::Result<()> {
    let mut head = format!(
        "HTTP/1.1 {status}\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Length: {}\r\nConnection: {}\r\n",
        body.len(),
        connection_word(keep_alive)
    );
    for (name, value) in extra {
        head.push_str(name);
        head.push_str(": ");
        head.push_str(value);
        head.push_str("\r\n");
    }
    head.push_str("\r\n");
    writer.write_all(head.as_bytes()).await?;
    if !head_only {
        writer.write_all(body.as_bytes()).await?;
    }
    Ok(())
}

/// Returns whether the connection may stay open for another request.
async fn route<W: AsyncWrite + Unpin>(
    request: &Request,
    writer: &mut W,
    config: &Config,
    keep_alive: bool,
) -> io::Result<bool> {
    let head_only = request.method == "HEAD";
    if request.method != "GET" && !head_only {
        simple(
            writer,
            "405 Method Not Allowed",
            "only GET and HEAD are supported\n",
            &[("Allow", "GET, HEAD")],
            keep_alive,
            false,
        )
        .await?;
        return Ok(keep_alive);
    }

    if head_only && request.query.contains_key("nohead") {
        simple(
            writer,
            "405 Method Not Allowed",
            "HEAD is not allowed here\n",
            &[("Allow", "GET")],
            keep_alive,
            true,
        )
        .await?;
        return Ok(keep_alive);
    }

    match request.path.as_str() {
        "/" | "/info" => {
            simple(writer, "200 OK", USAGE, &[], keep_alive, head_only).await?;
            Ok(keep_alive)
        }
        "/file" => serve_file(request, writer, config, keep_alive, head_only).await,
        "/redirect" => {
            let location = if request.raw_query.is_empty() {
                "/file".to_string()
            } else {
                format!("/file?{}", request.raw_query)
            };
            simple(
                writer,
                "302 Found",
                "redirecting to /file\n",
                &[("Location", &location)],
                keep_alive,
                head_only,
            )
            .await?;
            Ok(keep_alive)
        }
        "/auth" => {
            let allowed =
                request.headers.get("authorization").map(String::as_str) == Some(BASIC_AUTH);
            if allowed {
                serve_file(request, writer, config, keep_alive, head_only).await
            } else {
                simple(
                    writer,
                    "401 Unauthorized",
                    "authentication required\n",
                    &[("WWW-Authenticate", "Basic realm=\"mohona\"")],
                    keep_alive,
                    head_only,
                )
                .await?;
                Ok(keep_alive)
            }
        }
        "/login" => {
            simple(
                writer,
                "200 OK",
                "logged in\n",
                &[("Set-Cookie", "session=ok; Path=/")],
                keep_alive,
                head_only,
            )
            .await?;
            Ok(keep_alive)
        }
        "/cookie" => {
            let allowed = request
                .headers
                .get("cookie")
                .is_some_and(|value| value.split(';').any(|part| part.trim() == "session=ok"));
            if allowed {
                serve_file(request, writer, config, keep_alive, head_only).await
            } else {
                simple(
                    writer,
                    "403 Forbidden",
                    "cookie session=ok required\n",
                    &[],
                    keep_alive,
                    head_only,
                )
                .await?;
                Ok(keep_alive)
            }
        }
        "/referrer" => {
            if request.headers.contains_key("referer") {
                serve_file(request, writer, config, keep_alive, head_only).await
            } else {
                simple(
                    writer,
                    "403 Forbidden",
                    "Referer header required\n",
                    &[],
                    keep_alive,
                    head_only,
                )
                .await?;
                Ok(keep_alive)
            }
        }
        _ => {
            simple(
                writer,
                "404 Not Found",
                "not found\n",
                &[],
                keep_alive,
                head_only,
            )
            .await?;
            Ok(keep_alive)
        }
    }
}

fn query_u64(request: &Request, key: &str) -> Option<u64> {
    request.query.get(key).and_then(|value| value.parse().ok())
}

fn random_u64() -> u64 {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(1, |elapsed| elapsed.as_nanos() as u64);
    let mut x = nanos ^ COUNTER.fetch_add(0x9E37_79B9, Ordering::Relaxed) ^ 0x2545_F491_4F6C_DD1D;
    x ^= x << 13;
    x ^= x >> 7;
    x ^= x << 17;
    x
}

async fn serve_file<W: AsyncWrite + Unpin>(
    request: &Request,
    writer: &mut W,
    config: &Config,
    keep_alive: bool,
    head_only: bool,
) -> io::Result<bool> {
    let size = query_u64(request, "size").unwrap_or(config.default_size);
    let etag_tag = request.query.get("etag").map_or("1", String::as_str);
    let etag = format!("\"mohona-{size}-{etag_tag}\"");
    let no_range = request.query.contains_key("norange");
    let rate = query_u64(request, "limit").filter(|rate| *rate > 0);

    let if_range_matches = request
        .headers
        .get("if-range")
        .is_none_or(|value| *value == etag);
    let range_header = if no_range || !if_range_matches {
        None
    } else {
        request.headers.get("range")
    };

    let (status, start, len, content_range) = match range_header {
        None => ("200 OK", 0, size, None),
        Some(header) => match parse_range(header, size) {
            Some((first, last)) => (
                "206 Partial Content",
                first,
                last - first + 1,
                Some(format!("bytes {first}-{last}/{size}")),
            ),
            None => {
                let unsatisfied = format!("bytes */{size}");
                simple(
                    writer,
                    "416 Range Not Satisfiable",
                    "range not satisfiable\n",
                    &[("Content-Range", &unsatisfied)],
                    keep_alive,
                    head_only,
                )
                .await?;
                return Ok(keep_alive);
            }
        },
    };

    let drop_limit = query_u64(request, "drop_after").or_else(|| {
        let random = request
            .query
            .get("drop")
            .is_some_and(|value| value == "random");
        (random && len > 1).then(|| 1 + random_u64() % (len - 1))
    });

    let mut head = format!(
        "HTTP/1.1 {status}\r\nContent-Type: application/octet-stream\r\nContent-Length: {len}\r\nETag: {etag}\r\nLast-Modified: {LAST_MODIFIED}\r\nContent-Disposition: attachment; filename=\"mohona-test.bin\"\r\nConnection: {}\r\n",
        connection_word(keep_alive)
    );
    if !no_range {
        head.push_str("Accept-Ranges: bytes\r\n");
    }
    if let Some(content_range) = content_range {
        head.push_str("Content-Range: ");
        head.push_str(&content_range);
        head.push_str("\r\n");
    }
    head.push_str("\r\n");
    writer.write_all(head.as_bytes()).await?;
    if head_only {
        return Ok(keep_alive);
    }

    let rate = match query_u64(request, "slow_start").filter(|rate| *rate > 0) {
        Some(slow) if start == 0 => Some(slow),
        _ => rate,
    };
    let started = Instant::now();
    let mut buffer = vec![0u8; CHUNK];
    let mut sent = 0u64;
    while sent < len {
        let mut count = (len - sent).min(CHUNK as u64);
        if let Some(limit) = drop_limit {
            if sent >= limit {
                // Stop mid-body: the client sees the connection close early.
                return Ok(false);
            }
            count = count.min(limit - sent);
        }
        let count = count as usize;
        fill_content(start + sent, &mut buffer[..count]);
        writer.write_all(&buffer[..count]).await?;
        sent += count as u64;
        if let Some(rate) = rate {
            let due = Duration::from_secs_f64(sent as f64 / rate as f64);
            if let Some(wait) = due.checked_sub(started.elapsed()) {
                tokio::time::sleep(wait).await;
            }
        }
    }
    Ok(keep_alive)
}

#[cfg(test)]
mod tests {
    use super::{content_byte, parse_range};

    #[test]
    fn content_is_deterministic() {
        assert_eq!(content_byte(12345), content_byte(12345));
    }

    #[test]
    fn parses_closed_open_and_suffix_ranges() {
        assert_eq!(parse_range("bytes=0-99", 1000), Some((0, 99)));
        assert_eq!(parse_range("bytes=900-", 1000), Some((900, 999)));
        assert_eq!(parse_range("bytes=-100", 1000), Some((900, 999)));
        assert_eq!(parse_range("bytes=990-5000", 1000), Some((990, 999)));
    }

    #[test]
    fn rejects_bad_or_unsatisfiable_ranges() {
        assert_eq!(parse_range("bytes=1000-", 1000), None);
        assert_eq!(parse_range("bytes=50-10", 1000), None);
        assert_eq!(parse_range("items=0-1", 1000), None);
        assert_eq!(parse_range("bytes=-0", 1000), None);
        assert_eq!(parse_range("bytes=0-1", 0), None);
    }
}
